"""The Python ports must give exactly what the TypeScript they replaced gave.

tests/golden/*.json were generated by running the original server/src/features/ai code (foodParsing, recommendations,
weeklyInsight and the reports builder) over a broad input set. Run from ai_services/: python -m unittest discover tests
"""
import json
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.services.food_match import build_result, pick_best_food, regex_parse_food, search_terms  # noqa: E402
from app.services.recommendations import (  # noqa: E402
    build_reason, food_to_candidate, rank_meals, recipe_to_candidate, score_candidate,
)
from app.services.weekly_service import heuristic_report_insight  # noqa: E402

GOLDEN = os.path.join(os.path.dirname(os.path.abspath(__file__)), "golden")


def load(name):
    with open(os.path.join(GOLDEN, name), encoding="utf-8") as f:
        return json.load(f)


def norm(value):
    """Round-trip through JSON so int/float spelling (2 vs 2.0) cannot cause a false difference."""
    return json.loads(json.dumps(value))


class FoodParseParity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data = load("food_parse.json")

    def test_regex_parser_matches_on_every_input(self):
        for case in self.data["parsed"]:
            with self.subTest(text=case["text"][:40]):
                self.assertEqual(norm(regex_parse_food(case["text"])), case["items"])

    def test_search_terms_match(self):
        for case in self.data["terms"]:
            with self.subTest(name=case["name"]):
                self.assertEqual(search_terms(case["name"]), case["terms"])

    def test_best_food_pick_matches(self):
        pool = [{"name": n} for n in ["Apple pie", "Apple", "Green apple juice", "apple", "Apple "]]
        for case in self.data["best"]:
            with self.subTest(name=case["name"]):
                best = pick_best_food(case["name"], pool)
                self.assertEqual(best["name"] if best else None, case["best"])

    def test_match_and_scale_results_are_identical(self):
        self.assertGreater(len(self.data["results"]), 400)
        for case in self.data["results"]:
            with self.subTest(item=case["item"]["name"], food=(case["food"] or {}).get("name")):
                self.assertEqual(norm(build_result(case["item"], case["food"])), case["result"])


class RecommendationParity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data = load("recommendations.json")

    def test_candidates_are_built_identically(self):
        built = [c for c in [*map(food_to_candidate, self.data["rawFoods"]), *map(recipe_to_candidate, self.data["rawRecipes"])] if c]
        self.assertEqual(norm(built), self.data["candidates"])

    def test_ranking_is_identical_for_every_remaining_budget_and_limit(self):
        for case in self.data["ranking"]:
            with self.subTest(remaining=case["remaining"], limit=case["limit"]):
                self.assertEqual(norm(rank_meals(self.data["candidates"], case["remaining"], case["limit"])), case["result"])

    def test_scores_and_reasons_are_identical(self):
        for case in self.data["scores"]:
            with self.subTest(name=case["c"]["name"]):
                self.assertEqual(score_candidate(case["c"], case["remaining"]), case["score"])
                self.assertEqual(build_reason(case["c"], case["remaining"]), case["reason"])


class WeeklyParity(unittest.TestCase):
    def test_heuristic_insight_matches_for_every_week(self):
        cases = load("weekly.json")["weekly"]
        self.assertGreaterEqual(len(cases), 6)
        for case in cases:
            with self.subTest(case=case["name"]):
                self.assertEqual(norm(heuristic_report_insight(case["report"])), case["heuristic"])


if __name__ == "__main__":
    unittest.main()
