// Calendar dates on the client are the browser's local dates; the server buckets by the user's
// stored IANA timezone, which we keep equal to the browser's (see docs/timezone.md).

export const localDateString = (d: Date = new Date()): string => {
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

export const browserTimezone = (): string | undefined => {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || undefined;
  } catch {
    return undefined;
  }
};

/** Parse YYYY-MM-DD as a local calendar date (new Date('YYYY-MM-DD') is UTC midnight). */
export const parseLocalDate = (s: string): Date => {
  const [y, m, d] = s.split('-').map(Number);
  return new Date(y, m - 1, d);
};
